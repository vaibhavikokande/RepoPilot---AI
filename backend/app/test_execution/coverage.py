"""Coverage analysis parser and metrics calculator for test execution."""

import json
import logging
from pathlib import Path
from typing import Dict, List, Optional

from app.schemas.test_execution import CoverageReport, FileCoverage

logger = logging.getLogger(__name__)


class CoverageParser:
    """Parses and normalizes coverage.py JSON reports produced during test runs."""

    @staticmethod
    def parse_file(
        report_path: Path,
        repo_root: Optional[Path] = None,
        target_file: Optional[str] = None,
    ) -> CoverageReport:
        """Parse a coverage.json file into a structured CoverageReport.

        Args:
            report_path: Path to the generated coverage.json file.
            repo_root: Optional repository root to normalize absolute paths.
            target_file: Optional target file path to emphasize.

        Returns:
            CoverageReport with totals, per-file statistics, and missing lines.
        """
        if not report_path.is_file():
            return CoverageReport(
                is_available=False,
                reason="Coverage file was not generated by pytest-cov or was removed.",
            )

        try:
            content = report_path.read_text(encoding="utf-8", errors="replace").strip()
            if not content:
                return CoverageReport(
                    is_available=False,
                    reason="Coverage report file was empty.",
                )

            data = json.loads(content)
        except (json.JSONDecodeError, OSError) as exc:
            logger.warning("Failed to decode coverage report at %s: %s", report_path, exc)
            return CoverageReport(
                is_available=False,
                reason=f"Failed to parse coverage data: {str(exc)}",
            )

        return CoverageParser.parse_dict(data, repo_root=repo_root, target_file=target_file)

    @staticmethod
    def parse_dict(
        data: Dict,
        repo_root: Optional[Path] = None,
        target_file: Optional[str] = None,
    ) -> CoverageReport:
        """Parse raw coverage JSON dictionary into CoverageReport."""
        files_dict = data.get("files", {})
        totals_dict = data.get("totals", {})

        if not files_dict and not totals_dict:
            return CoverageReport(
                is_available=False,
                reason="Coverage data contained no tracked files or totals.",
            )

        file_coverages: List[FileCoverage] = []

        for raw_path, file_data in files_dict.items():
            norm_path = CoverageParser._normalize_path(raw_path, repo_root)

            # Skip test files and virtualenv / python library files from coverage report
            if norm_path.startswith("test") or "/site-packages/" in norm_path:
                continue

            summary = file_data.get("summary", {})
            num_statements = summary.get("num_statements", 0)
            covered_lines = summary.get("covered_lines", 0)
            missing_count = summary.get("missing_lines", 0)
            percent_covered = summary.get("percent_covered", 0.0)

            # Missing lines list
            missing_lines_raw = file_data.get("missing_lines", [])
            missing_lines = [int(line) for line in missing_lines_raw if isinstance(line, (int, str)) and str(line).isdigit()]

            file_coverages.append(
                FileCoverage(
                    file_path=norm_path,
                    total_statements=num_statements,
                    covered_statements=covered_lines,
                    missing_statements=missing_count,
                    coverage_percent=round(float(percent_covered), 2),
                    missing_lines=missing_lines,
                )
            )

        # Sort file coverages so target_file comes first if specified, then by file_path
        if target_file:
            norm_target = target_file.strip().lstrip("/")
            file_coverages.sort(key=lambda f: (0 if f.file_path == norm_target else 1, f.file_path))
        else:
            file_coverages.sort(key=lambda f: f.file_path)

        total_statements = totals_dict.get("num_statements", sum(f.total_statements for f in file_coverages))
        covered_statements = totals_dict.get("covered_lines", sum(f.covered_statements for f in file_coverages))
        missing_statements = totals_dict.get("missing_lines", sum(f.missing_statements for f in file_coverages))

        if total_statements > 0:
            coverage_percent = round((covered_statements / total_statements) * 100.0, 2)
        else:
            coverage_percent = 0.0

        return CoverageReport(
            total_statements=total_statements,
            covered_statements=covered_statements,
            missing_statements=missing_statements,
            coverage_percent=coverage_percent,
            files=file_coverages,
            is_available=True,
            reason=None,
        )

    @staticmethod
    def _normalize_path(raw_path: str, repo_root: Optional[Path] = None) -> str:
        """Strip container workspace prefixes or host temp directory prefixes."""
        p_str = str(raw_path).replace("\\", "/")

        # Strip docker /workspace/ prefix
        if p_str.startswith("/workspace/"):
            return p_str.replace("/workspace/", "", 1)
        if p_str.startswith("workspace/"):
            return p_str.replace("workspace/", "", 1)

        # Strip repo_root if given
        if repo_root:
            root_str = str(repo_root).replace("\\", "/")
            if p_str.startswith(root_str):
                return p_str[len(root_str):].lstrip("/")

        # If it looks like an absolute path, try to find repository relative part
        parts = p_str.split("/")
        # Find index of common repository folders: app, src, backend, etc.
        for idx, segment in enumerate(parts):
            if segment in ("app", "src", "backend", "tests", "lib"):
                return "/".join(parts[idx:])

        return p_str.lstrip("/")
